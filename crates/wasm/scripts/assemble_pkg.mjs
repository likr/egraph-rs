#!/usr/bin/env node
import { readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const crateDir = path.resolve(scriptDir, "..");
const pkgDir = path.join(crateDir, "pkg");

const wasmJsPath = path.join(pkgDir, "egraph_wasm.js");
const wasmDtsPath = path.join(pkgDir, "egraph_wasm.d.ts");
const wasmBinPath = path.join(pkgDir, "egraph_wasm_bg.wasm");

const [wasmJs, wasmDts] = await Promise.all([
  readFile(wasmJsPath, "utf8"),
  readFile(wasmDtsPath, "utf8"),
  readFile(wasmBinPath),
]);

// Collect all named exports generated by wasm-bindgen in egraph_wasm.js so both full
// and `--no-default-features` builds expose their exact symbol surface cleanly.
const exportedNames = new Set();
for (const match of wasmJs.matchAll(/^export\s+(?:class|function)\s+([A-Za-z0-9_$]+)/gm)) {
  exportedNames.add(match[1]);
}
for (const match of wasmJs.matchAll(/^export\s*\{([^}]+)\}\s*;?/gm)) {
  for (const part of match[1].split(",")) {
    const trimmed = part.trim();
    if (!trimmed) continue;
    const asMatch = trimmed.match(/^(?:[A-Za-z0-9_$]+)\s+as\s+([A-Za-z0-9_$]+)$/);
    const name = asMatch ? asMatch[1] : trimmed;
    if (name !== "default") {
      exportedNames.add(name);
    }
  }
}

const requiredCoreAndM1 = [
  "Layout2d",
  "CsrGraph",
  "wasmMemory",
  "initSync",
  "scaleNormalizedStress",
  "evaluateMetrics",
  "MetricReport",
  "PrismDistortion",
];

const requiredM2 = [
  "KnnGraph",
  "SparseProbabilities",
  "DogVaradhanLandmarks",
  "EigenResult",
  "SpectralMomentStats",
  "TwoHopCsr",
  "TwoHopKnnResult",
  "HybridKnnResult",
  "selectMaxminSpPivots",
  "pivotMdsInit",
  "korenSpectralInit",
  "smallestLaplacianEigenpairs",
  "spectralMomentStats",
  "chebyshevHeatSpmv",
  "chebyshevDogJlEmbedding",
  "extract1hop2hopCsr",
  "buildPure2hopKnn",
  "compute2hopNeighborhoodSizes",
  "computeNodewise2hopPerplexities",
  "computeMedian2hopPerplexity",
  "buildHybridAdaptiveKnn",
  "partialBfsKnn",
  "computeKnnProbabilities",
  "computeFuzzySimplicialSet",
  "findAbParams",
  "computeHorvitzThompsonGamma",
  "computeRegularizedDogVaradhanLandmarks",
];

const missingExports = [...requiredCoreAndM1, ...requiredM2].filter(
  (name) => !exportedNames.has(name),
);
if (missingExports.length > 0) {
  throw new Error(
    `Missing required v6 exports in ${wasmJsPath}: ${missingExports.join(", ")}; found: ${Array.from(exportedNames).join(", ")}`,
  );
}

const passthroughExports = Array.from(exportedNames)
  .filter((name) => name !== "Layout2d")
  .sort();

const indexJs = `/* @ts-self-types="./index.d.ts" */
import init, {
  Layout2d as _Layout2d,
${passthroughExports.map((name) => `  ${name},`).join("\n")}
} from "./egraph_wasm.js";

function attachCoordsView(Layout2dClass) {
  if (typeof Layout2dClass.prototype.coordsView !== "function") {
    Layout2dClass.prototype.coordsView = function coordsView() {
      const buf = wasmMemory().buffer;
      const ptr = this.coordsPtr();
      const len = this.coordsLen();
      if (
        !this._coordsView ||
        this._coordsViewBuf !== buf ||
        this._coordsView.byteOffset !== ptr ||
        this._coordsView.length !== len
      ) {
        this._coordsView = new Float32Array(buf, ptr, len);
        this._coordsViewBuf = buf;
      }
      return this._coordsView;
    };
  }
  return Layout2dClass;
}

export const Layout2d = attachCoordsView(_Layout2d);
export {
${passthroughExports.map((name) => `  ${name},`).join("\n")}
};
export default init;
`;

const nodeJs = `/* @ts-self-types="./index.d.ts" */
import { readFile } from "node:fs/promises";
import { initSync } from "./egraph_wasm.js";

const wasmBytes = await readFile(new URL("./egraph_wasm_bg.wasm", import.meta.url));
const wasmExports = initSync({ module: wasmBytes });

export * from "./index.js";

export default async function init() {
  return wasmExports;
}
`;

// Build pkg/index.d.ts from egraph_wasm.d.ts, preserving all v6 and legacy declarations
// while adding CsrGraphOptions and Layout2d.prototype.coordsView().
let indexDts = wasmDts;

const csrOptionsDecl = `/**
 * Options controlling CSR / edge-list graph construction.
 */
export interface CsrGraphOptions {
    directed?: boolean;
    sanitize?: boolean;
}

`;

if (!indexDts.includes("export interface CsrGraphOptions")) {
  indexDts = indexDts.replace("export class CsrGraph {", `${csrOptionsDecl}export class CsrGraph {`);
}

indexDts = indexDts.replace(
  /static fromCsr\([^;]+\): CsrGraph;/,
  `static fromCsr(indptr: Uint32Array | number[], indices: Uint32Array | number[], weights?: Float32Array | number[] | null, options?: boolean | CsrGraphOptions | null, sanitize?: boolean | null): CsrGraph;`,
);

indexDts = indexDts.replace(
  /static fromEdgeList\([^;]+\): CsrGraph;/,
  `static fromEdgeList(numNodes: number, edges: Uint32Array | number[], weights?: Float32Array | number[] | null, options?: boolean | CsrGraphOptions | null, sanitize?: boolean | null): CsrGraph;`,
);

const coordsViewDecl = `    /**
     * Returns a zero-copy \`Float32Array\` view over the interleaved \`[x0, y0, ...]\`
     * coordinates in WebAssembly linear memory, automatically refreshing the view
     * whenever \`memory.grow\` detaches the underlying \`ArrayBuffer\`.
     */
    coordsView(): Float32Array;
`;

if (!indexDts.includes("coordsView(): Float32Array;")) {
  const updated = indexDts.replace(
    /(export class Layout2d \{[\s\S]*?coordsPtr\(\): number;\n)/,
    `$1${coordsViewDecl}`,
  );
  if (updated === indexDts) {
    throw new Error(`Failed to inject coordsView() into Layout2d declaration in ${wasmDtsPath}`);
  }
  indexDts = updated;
}

const m1TypesDecl = `/**
 * Canonical target identifiers and normalized aliases accepted by \`evaluateMetrics\`.
 */
export type MetricTarget =
    | "scaleNormalizedStress"
    | "sampledScaleNormalizedStress"
    | "crossingNumber"
    | "crossingAngle"
    | "sampledCrossingNumber"
    | "neighborhoodPreservation1Hop"
    | "neighborhoodPreservation2Hop"
    | "gabrielGraphProperty"
    | "nodeResolution"
    | "relativeNeighborhoodPreservation"
    | "gabrielGraphPreservation"
    | "aspectRatio"
    | "angularResolution"
    | "idealEdgeLengths"
    | "sns"
    | "sampled_sns"
    | "np1"
    | "np2"
    | "drng"
    | "dgg";

/**
 * Plain JavaScript record returned by \`MetricReport.toRecord()\`.
 */
export interface MetricReportRecord {
    scaleNormalizedStress?: number;
    sampledScaleNormalizedStress?: number;
    crossingNumber?: number;
    crossingAngle?: number;
    sampledCrossingNumber?: number;
    neighborhoodPreservation1Hop?: number;
    neighborhoodPreservation2Hop?: number;
    gabrielGraphProperty?: number;
    nodeResolution?: number;
    relativeNeighborhoodPreservation?: number;
    gabrielGraphPreservation?: number;
    aspectRatio?: number;
    angularResolution?: number;
    idealEdgeLengths?: number;
}

`;

if (indexDts.includes("export class MetricReport {") && !indexDts.includes("export interface MetricReportRecord")) {
  const metricDocMarker = "/**\n * Selective quality metric report";
  if (indexDts.includes(metricDocMarker)) {
    indexDts = indexDts.replace(metricDocMarker, `${m1TypesDecl}${metricDocMarker}`);
  } else {
    indexDts = indexDts.replace("export class MetricReport {", `${m1TypesDecl}export class MetricReport {`);
  }
}

indexDts = indexDts.replace(
  /toRecord\(\): object;/,
  "toRecord(): MetricReportRecord;",
);

indexDts = indexDts.replace(
  /export function evaluateMetrics\([^;]+\): MetricReport;/,
  "export function evaluateMetrics(graph: CsrGraph, layout: Layout2d, targets: readonly (MetricTarget | string)[], numPivots?: number | null, numSamples?: number | null, seed?: number | null): MetricReport;",
);

indexDts = indexDts.replace(
  /export function prismDistortion\([^;]+\): PrismDistortion;/,
  "export function prismDistortion(originalLayout: Layout2d, adjustedLayout: Layout2d): PrismDistortion;",
);

indexDts = indexDts.replace(
  /export function sampledCrossingNumber\([^;]+\): number;/,
  "export function sampledCrossingNumber(graph: CsrGraph, layout: Layout2d, numSamples?: number | null, seed?: number | null): number;",
);

indexDts = indexDts.replace(
  /export function sampledScaleNormalizedStress\([^;]+\): number;/,
  "export function sampledScaleNormalizedStress(graph: CsrGraph, layout: Layout2d, numPivots?: number | null, seed?: number | null): number;",
);

// Refine M2 TypeScript signatures (camelCase parameter names, optional targetStd?: number | null).
const m2DtsReplacements = [
  [
    /static fromCsr\(num_nodes: number, indptr: Uint32Array \| number\[\], indices: Uint32Array \| number\[\], distances: Float64Array \| number\[\]\): KnnGraph;/,
    "static fromCsr(numNodes: number, indptr: Uint32Array | number[], indices: Uint32Array | number[], distances: Float64Array | number[]): KnnGraph;",
  ],
  [
    /export function selectMaxminSpPivots\([^;]+\): Uint32Array;/,
    "export function selectMaxminSpPivots(graph: CsrGraph, numPivots?: number | null, seed?: number | null, minDegree?: number | null): Uint32Array;",
  ],
  [
    /export function pivotMdsInit\([^;]+\): Layout2d;/,
    "export function pivotMdsInit(graph: CsrGraph, numPivots?: number | null, seed?: number | null, minDegree?: number | null, targetStd?: number | null): Layout2d;",
  ],
  [
    /export function korenSpectralInit\([^;]+\): Layout2d;/,
    "export function korenSpectralInit(graph: CsrGraph, targetStd?: number | null, tol?: number | null, maxIters?: number | null, seed?: number | null): Layout2d;",
  ],
  [
    /export function smallestLaplacianEigenpairs\([^;]+\): EigenResult;/,
    "export function smallestLaplacianEigenpairs(graph: CsrGraph, nModes?: number | null, tol?: number | null, maxIters?: number | null, seed?: number | null): EigenResult;",
  ],
  [
    /export function chebyshevHeatSpmv\([^;]+\): Float64Array;/,
    "export function chebyshevHeatSpmv(graph: CsrGraph, vectors: Float64Array | number[], numCols: number, t: number, degree?: number | null, lambdaMax?: number | null): Float64Array;",
  ],
  [
    /export function chebyshevDogJlEmbedding\([^;]+\): Float64Array;/,
    "export function chebyshevDogJlEmbedding(graph: CsrGraph, jlDim?: number | null, degree?: number | null, seed?: number | null, degreeNormalize?: boolean | null, epsPsd?: number | null, t1?: number | null, t2?: number | null, alpha?: number | null): Float64Array;",
  ],
  [
    /export function computeNodewise2hopPerplexities\([^;]+\): Float64Array;/,
    "export function computeNodewise2hopPerplexities(graph: CsrGraph, c?: number | null, minPerplexity?: number | null, maxPerplexity?: number | null): Float64Array;",
  ],
  [
    /export function computeMedian2hopPerplexity\([^;]+\): number;/,
    "export function computeMedian2hopPerplexity(graph: CsrGraph, c?: number | null, minPerplexity?: number | null, maxPerplexity?: number | null): number;",
  ],
  [
    /export function buildHybridAdaptiveKnn\([^;]+\): HybridKnnResult;/,
    "export function buildHybridAdaptiveKnn(graph: CsrGraph, coords: Float64Array | number[], dim: number, perplexities: Float64Array | number[], kFactor?: number | null, marginGap?: number | null, coarseDim?: number | null, rerankFactor?: number | null, k?: number | null, maxRowK?: number | null): HybridKnnResult;",
  ],
  [
    /export function computeKnnProbabilities\([^;]+\): SparseProbabilities;/,
    "export function computeKnnProbabilities(knn: KnnGraph, perplexities: Float64Array | number[], power?: number | null, sigmaIters?: number | null, sigmaTolerance?: number | null, rowNormalize?: boolean | null): SparseProbabilities;",
  ],
  [
    /export function computeFuzzySimplicialSet\([^;]+\): SparseProbabilities;/,
    "export function computeFuzzySimplicialSet(knn: KnnGraph, sigmaIters?: number | null, sigmaTolerance?: number | null): SparseProbabilities;",
  ],
  [
    /export function findAbParams\([^;]+\): Float64Array;/,
    "export function findAbParams(minDist?: number | null, spread?: number | null): Float64Array;",
  ],
  [
    /export function computeHorvitzThompsonGamma\([^;]+\): number;/,
    "export function computeHorvitzThompsonGamma(gammaNon2: number, numNodes: number, negPerNode: number): number;",
  ],
  [
    /export function computeRegularizedDogVaradhanLandmarks\([^;]+\): DogVaradhanLandmarks;/,
    "export function computeRegularizedDogVaradhanLandmarks(graph: CsrGraph, degree?: number | null, numLandmarks?: number | null, seed?: number | null, degreeNormalize?: boolean | null, pExp?: number | null, epsPsd?: number | null, tCoarse?: number | null, t1?: number | null, t2?: number | null, alpha?: number | null, betaFloor?: number | null): DogVaradhanLandmarks;",
  ],
];

for (const [pattern, replacement] of m2DtsReplacements) {
  const updated = indexDts.replace(pattern, replacement);
  if (updated === indexDts) {
    throw new Error(`Failed to refine M2 TypeScript declaration matching ${pattern} in ${wasmDtsPath}`);
  }
  indexDts = updated;
}

await Promise.all([
  writeFile(path.join(pkgDir, "index.js"), indexJs, "utf8"),
  writeFile(path.join(pkgDir, "egraph_wasm.node.js"), nodeJs, "utf8"),
  writeFile(path.join(pkgDir, "index.d.ts"), indexDts, "utf8"),
  // Remove wasm-pack's inner manifest/gitignore so crates/wasm/package.json stays authoritative.
  rm(path.join(pkgDir, "package.json"), { force: true }),
  rm(path.join(pkgDir, ".gitignore"), { force: true }),
]);

console.log(
  `[assemble_pkg] wrote index.js, egraph_wasm.node.js, and index.d.ts (${passthroughExports.length + 1} exports)`,
);
