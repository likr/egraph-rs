#!/usr/bin/env node
import { readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { buildIndexDts } from "./assemble/dts_builder.mjs";
import { buildIndexJs, buildNodeWrapperJs } from "./assemble/js_wrappers.mjs";
import { verifyRequiredExports } from "./assemble/required_exports.mjs";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const crateDir = path.resolve(scriptDir, "..");
const pkgDir = path.join(crateDir, "pkg");

const wasmJsPath = path.join(pkgDir, "egraph_wasm.js");
const wasmDtsPath = path.join(pkgDir, "egraph_wasm.d.ts");
const wasmBinPath = path.join(pkgDir, "egraph_wasm_bg.wasm");

const [wasmJs, wasmDts] = await Promise.all([
  readFile(wasmJsPath, "utf8"),
  readFile(wasmDtsPath, "utf8"),
  readFile(wasmBinPath),
]);

// Collect all named exports generated by wasm-bindgen in egraph_wasm.js so both full
// and `--no-default-features` builds expose their exact symbol surface cleanly.
const exportedNames = new Set();
for (const match of wasmJs.matchAll(/^export\s+(?:class|function)\s+([A-Za-z0-9_$]+)/gm)) {
  exportedNames.add(match[1]);
}
for (const match of wasmJs.matchAll(/^export\s*\{([^}]+)\}\s*;?/gm)) {
  for (const part of match[1].split(",")) {
    const trimmed = part.trim();
    if (!trimmed) continue;
    const asMatch = trimmed.match(/^(?:[A-Za-z0-9_$]+)\s+as\s+([A-Za-z0-9_$]+)$/);
    const name = asMatch ? asMatch[1] : trimmed;
    if (name !== "default") {
      exportedNames.add(name);
    }
  }
}

verifyRequiredExports(exportedNames, wasmJsPath);

const { indexJs, exportCount } = buildIndexJs(exportedNames);
const nodeJs = buildNodeWrapperJs();
const indexDts = buildIndexDts(wasmDts, wasmDtsPath);

await Promise.all([
  writeFile(path.join(pkgDir, "index.js"), indexJs, "utf8"),
  writeFile(path.join(pkgDir, "egraph_wasm.node.js"), nodeJs, "utf8"),
  writeFile(path.join(pkgDir, "index.d.ts"), indexDts, "utf8"),
  // Remove wasm-pack's inner manifest/gitignore so crates/wasm/package.json stays authoritative.
  rm(path.join(pkgDir, "package.json"), { force: true }),
  rm(path.join(pkgDir, ".gitignore"), { force: true }),
]);

console.log(
  `[assemble_pkg] wrote index.js, egraph_wasm.node.js, and index.d.ts (${exportCount} exports)`,
);
