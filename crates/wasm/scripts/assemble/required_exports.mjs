export function verifyRequiredExports(exportedNames, wasmJsPath) {
  const missingExports = requiredWasmExports.filter((name) => !exportedNames.has(name));
  if (missingExports.length > 0) {
    throw new Error(
      `Missing required exports in ${wasmJsPath}: ${missingExports.join(", ")}; found: ${Array.from(exportedNames).join(", ")}`,
    );
  }
}
